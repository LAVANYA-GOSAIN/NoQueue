# 5. Evaluation Function
# =====================================================================

def evaluate_agent(
    agent: ContextualBanditAgent,
    trials: int = 100
) -> Dict[str, Any]:
    """
    Evaluate the learned contextual bandit policy against a baseline that selects
    the minimum journey time station under identical initial conditions.
    """
    original_epsilon = agent.epsilon
    agent.epsilon = 0.0

    try:
        rl_journey_times: List[float] = []
        baseline_journey_times: List[float] = []
        fallback_count = 0

        for _ in range(trials):
            env = CNGEnvironment(STATIONS)
            contexts = env.reset()
            fallback_times = env.get_deterministic_journey_times()

            chosen_action, mode, fallback_used = agent.choose_action(
                station_contexts=contexts,
                fallback_journey_times=fallback_times,
                explore=False
            )

            if fallback_used:
                fallback_count += 1

            # Evaluate chosen station
            rl_env = copy.deepcopy(env)
            _, _, rl_details = rl_env.step(chosen_action)
            rl_journey_times.append(rl_details["total_journey_time"])

            # Baseline selects minimum journey time
            best_baseline_time = min(fallback_times.values())
            baseline_journey_times.append(best_baseline_time)

        rl_avg = sum(rl_journey_times) / trials if trials > 0 else 0.0
        baseline_avg = sum(baseline_journey_times) / trials if trials > 0 else 0.0
        difference = round(rl_avg - baseline_avg, 2)

        print(f"Number of evaluation trials: {trials}")
        print(f"Bandit average journey time: {rl_avg:.2f} mins")
        print(f"Baseline average journey time: {baseline_avg:.2f} mins")
        print(f"Difference: {difference:.2f} mins")
        print(f"Fallback activations during eval: {fallback_count}/{trials}")
        print(f"Contexts in model: {len(agent.q_table)}/36")

        return {
            "trials": trials,
            "rl_average_journey_time": round(rl_avg, 2),
            "baseline_average_journey_time": round(baseline_avg, 2),
            "difference": difference,
            "fallback_count": fallback_count,
            "contexts_covered": len(agent.q_table),
            "rl_journey_times": rl_journey_times,
            "baseline_journey_times": baseline_journey_times
        }
    finally:
        agent.epsilon = original_epsilon


