"""
NoQueue - Contextual Bandit Recommendation Engine (rl_engine_v2.py)
===================================================================
A single-decision contextual bandit system for CNG station recommendation.

IMPORTANT DISCLAIMER:
---------------------
This engine operates strictly on synthetic, simulated demonstration data.
It does NOT use live CCTV measurements, nor does it claim to alter or improve
real-world physical CNG queue conditions.

Key Architecture Changes from Legacy Multi-Step Q-Learning:
------------------------------------------------------------
1. State/Context Representation:
   Replaces the combinatorial 6,561-state joint representation with
   station-specific contexts:
       S{station_id}_{traffic_level}_{queue_level}
   (e.g., S1_MODERATE_LOW). Total possible contexts across 4 stations: 36.

2. Single-Decision Policy (Gamma = 0):
   Recommendation is an episodic point-in-time decision (which station is optimal
   for the current trip), so gamma = 0. The Bellman update simplifies to:
       Q(c, a) = Q(c, a) + alpha * [reward - Q(c, a)]
   where reward = -total_journey_time.

3. Deterministic Minimum Journey-Time Fallback:
   If an unseen context is encountered during recommendation, the engine falls
   back to computing estimated journey times (travel + queue / service_rate) and
   picks the minimum journey time station. Random selection is NEVER used in recommendation.

4. Model Persistence:
   Saves to `contextual_bandit_model.json`. Preserves the legacy `q_table_v2.json`.
"""

