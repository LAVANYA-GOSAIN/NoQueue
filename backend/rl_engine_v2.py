# 2. Contextual Bandit Agent Class
# =====================================================================

class ContextualBanditAgent:
    """
    Contextual Bandit agent for CNG station recommendation.
    
    Uses station-specific contexts (S{station_id}_{traffic}_{queue}) with
    gamma = 0 (single-decision recommendation).
    """

    def __init__(
        self,
        actions: Optional[List[int]] = None,
        alpha: float = 0.1,
        epsilon: float = 0.2
    ):
        self.actions = actions if actions is not None else [1, 2, 3, 4]
        self.alpha = alpha
        self.gamma = 0.0  # Single-decision recommendation
        self.epsilon = epsilon

        # Q-table mapping: (context_string, action_id) -> expected_reward (negative journey time)
        self.q_table: Dict[Tuple[str, int], float] = {}
        self.visit_counts: Dict[Tuple[str, int], int] = {}

    def get_q_value(self, context: str, action: int) -> Optional[float]:
        """Returns learned Q-value for (context, action) or None if unseen."""
        return self.q_table.get((context, action), None)

    def learn(
        self,
        context: str,
        action: int,
        reward: float,
        next_state: Any = None,
        done: bool = True
    ) -> float:
        """
        Contextual Bandit update (gamma = 0):
        Q(c, a) = Q(c, a) + alpha * [reward - Q(c, a)]
        """
        current_q = self.q_table.get((context, action))

        if current_q is None:
            new_q = reward
        else:
            new_q = current_q + self.alpha * (reward - current_q)

        self.q_table[(context, action)] = round(new_q, 4)
        self.visit_counts[(context, action)] = (
            self.visit_counts.get((context, action), 0) + 1
        )
        return self.q_table[(context, action)]

    def choose_action(
        self,
        station_contexts: Dict[int, str],
        fallback_journey_times: Optional[Dict[int, float]] = None,
        explore: bool = True
    ) -> Tuple[int, str, bool]:
        """
        Selects an action using epsilon-greedy during training or exploitation
        during recommendation.
        
        Returns:
            (chosen_station_id, decision_mode, fallback_status)
        """
        # Epsilon-greedy exploration (only during training)
        if explore and random.random() < self.epsilon:
            return random.choice(self.actions), "exploration", False

        # Check if all candidate stations have learned Q-values for their respective contexts
        all_learned = all(
            (station_contexts[a], a) in self.q_table
            for a in self.actions
            if a in station_contexts
        )

        if all_learned:
            # Exploitation: Each station is evaluated using its OWN context
            best_action = max(
                self.actions,
                key=lambda a: self.q_table[(station_contexts[a], a)]
            )
            return best_action, "learned_policy", False
        else:
            # Deterministic fallback: minimum estimated journey time (never random!)
            if fallback_journey_times:
                best_action = min(
                    self.actions,
                    key=lambda a: fallback_journey_times.get(a, float("inf"))
                )
            else:
                best_action = max(
                    self.actions,
                    key=lambda a: self.q_table.get((station_contexts.get(a, ""), a), -float("inf"))
                )
            return best_action, "deterministic_fallback", True

    def save_model(self, filepath: str) -> None:
        """Save learned contextual bandit model to JSON."""
        records = [
            {
                "context": context,
                "action": action,
                "q_value": value,
                "visits": self.visit_counts.get((context, action), 0)
            }
            for (context, action), value in sorted(self.q_table.items())
        ]

        payload = {
            "model_type": "contextual_bandit",
            "gamma": self.gamma,
            "alpha": self.alpha,
            "total_possible_contexts": 36,
            "learned_contexts_count": len(self.q_table),
            "records": records
        }

        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, "w") as file:
            json.dump(payload, file, indent=4)

        print(f"Model saved to: {filepath} ({len(self.q_table)}/36 contexts learned)")

    def save_q_table(self, filepath: str) -> None:
        """Alias for save_model."""
        self.save_model(filepath)

    def load_model(self, filepath: str) -> None:
        """Load contextual bandit model from JSON."""
        if not os.path.exists(filepath):
            raise FileNotFoundError(f"Model file not found: {filepath}")

        with open(filepath, "r") as file:
            data = json.load(file)

        records = data.get("records", data) if isinstance(data, dict) else data

        self.q_table = {
            (record.get("context", record.get("state")), int(record["action"])):
            float(record["q_value"])
            for record in records
        }

        self.visit_counts = {
            (record.get("context", record.get("state")), int(record["action"])):
            int(record.get("visits", 1))
            for record in records
        }

        print(f"Loaded {len(self.q_table)} contextual bandit entries from: {filepath}")

    def load_q_table(self, filepath: str) -> None:
        """Alias for load_model."""
        self.load_model(filepath)


