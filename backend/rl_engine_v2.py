# 3. Training Function
# =====================================================================

def train_agent(
    episodes: int = 1000,
    max_steps: int = 1,
    alpha: float = 0.1,
    epsilon: float = 0.25,
    model_save_path: Optional[str] = None
) -> Tuple[ContextualBanditAgent, Dict[str, Any]]:
    """
    Train the Contextual Bandit agent using single-decision simulated CNG scenarios.
    Gamma = 0.
    """
    if model_save_path is None:
        model_save_path = MODEL_PATH

    env = CNGEnvironment(STATIONS)
    actions = env.get_available_actions()

    agent = ContextualBanditAgent(
        actions=actions,
        alpha=alpha,
        epsilon=epsilon
    )

    training_rewards: List[float] = []

    # All 36 theoretical contexts
    all_possible_contexts = {
        f"S{s_id}_{traffic}_{queue}"
        for s_id in actions
        for traffic in ["LOW", "MODERATE", "HEAVY"]
        for queue in ["LOW", "MODERATE", "HIGH"]
    }

    for episode in range(episodes):
        contexts = env.reset()
        fallbacks = env.get_deterministic_journey_times()

        # Contextual action selection
        action, _, _ = agent.choose_action(
            contexts,
            fallbacks,
            explore=True
        )

        # Environment returns immediate reward = -total_journey_time
        _, reward, details = env.step(action)

        # Update Q(c_action, action) with gamma = 0
        chosen_context = contexts[action]
        agent.learn(chosen_context, action, reward)

        training_rewards.append(reward)

        # Epsilon decay
        agent.epsilon = max(0.05, agent.epsilon * 0.997)

        if (episode + 1) % 200 == 0:
            avg_rew = sum(training_rewards[-200:]) / 200
            print(
                f"Episode {episode + 1}/{episodes} | "
                f"Average Reward: {avg_rew:.2f} | "
                f"Epsilon: {agent.epsilon:.3f} | "
                f"Contexts Learned: {len(agent.q_table)}/{len(all_possible_contexts)}"
            )

    learned_count = len(agent.q_table)
    total_count = len(all_possible_contexts)
    coverage_pct = round((learned_count / total_count) * 100, 1)

    print("\nTraining completed!")
    print(f"Total episodes: {episodes}")
    print(f"Verified context coverage: {learned_count}/{total_count} ({coverage_pct}%)")

    # Save to contextual_bandit_model.json
    agent.save_model(model_save_path)

    training_summary = {
        "episodes": episodes,
        "learned_contexts": learned_count,
        "total_possible_contexts": total_count,
        "coverage_percentage": coverage_pct,
        "final_average_reward": round(sum(training_rewards[-100:]) / 100, 2)
    }

    return agent, training_summary


