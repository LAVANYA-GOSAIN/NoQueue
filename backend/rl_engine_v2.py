# 4. Recommendation Function
# =====================================================================

def recommend_station(
    stations: Optional[List[Dict[str, Any]]] = None,
    agent: Optional[ContextualBanditAgent] = None,
    station_conditions: Optional[Dict[int, Dict[str, Any]]] = None,
    model_path: Optional[str] = None
) -> Dict[str, Any]:
    """
    Recommends the optimal CNG station using the learned contextual bandit model.
    If an unseen context is encountered, uses a deterministic minimum journey-time fallback.
    Never selects randomly.
    """
    if stations is None:
        stations = STATIONS

    station_map = {s["id"]: s for s in stations}
    actions = list(station_map.keys())

    # Load agent if not provided
    if agent is None:
        if model_path is None:
            model_path = MODEL_PATH

        agent = ContextualBanditAgent(actions=actions)
        if os.path.exists(model_path):
            agent.load_model(model_path)
        else:
            # Train model if not yet created
            agent, _ = train_agent(episodes=1000, model_save_path=model_path)

    contexts: Dict[int, str] = {}
    calculated_times: Dict[int, Dict[str, Any]] = {}

    for s_id in actions:
        st = station_map[s_id]
        cond = (station_conditions or {}).get(s_id, {})

        traffic = cond.get("traffic", cond.get("traffic_level", "MODERATE")).upper()
        if traffic not in ["LOW", "MODERATE", "HEAVY"]:
            traffic = "MODERATE"

        queue = cond.get("queue", cond.get("vehicles_in_queue", cond.get("queue_length", 5)))
        service_rate = cond.get("service_rate", cond.get("service_rate_per_minute", 1.0))

        if queue <= 5:
            queue_level = "LOW"
        elif queue <= 12:
            queue_level = "MODERATE"
        else:
            queue_level = "HIGH"

        context_str = f"S{s_id}_{traffic}_{queue_level}"
        contexts[s_id] = context_str

        # Check if station provides raw road duration (e.g. from OSRM) or legacy simulated base
        if st.get("routing_engine") == "osrm" or st.get("is_road_network") or ("travel_time_minutes" in st and "base_travel_time" in st and st["travel_time_minutes"] == st["base_travel_time"]):
            travel_time = round(float(st.get("travel_time_minutes", st.get("base_travel_time", 10.0))), 1)
        else:
            traffic_mult = {
                "LOW": 0.8,
                "MODERATE": 1.0,
                "HEAVY": 1.5
            }.get(traffic, 1.0)
            base_travel = float(
                st.get("base_travel_time", st.get("travel_time_minutes", 10.0))
            )
            travel_time = round(base_travel * traffic_mult, 1)

        waiting_time = round(queue / max(float(service_rate), 0.1), 1)
        total_time = round(travel_time + waiting_time, 1)

        calculated_times[s_id] = {
            "travel_time": travel_time,
            "waiting_time": waiting_time,
            "total_journey_time": total_time,
            "traffic": traffic,
            "queue_level": queue_level
        }

    # Verify if all contexts have been learned in the Q-table
    all_contexts_learned = all(
        (contexts[s_id], s_id) in agent.q_table
        for s_id in actions
    )

    fallback_times_map = {
        s_id: calculated_times[s_id]["total_journey_time"]
        for s_id in actions
    }

    if all_contexts_learned:
        # Each station is evaluated using its OWN context!
        chosen_id, decision_mode, fallback_status = agent.choose_action(
            station_contexts=contexts,
            fallback_journey_times=fallback_times_map,
            explore=False
        )
        predicted_q = agent.get_q_value(contexts[chosen_id], chosen_id)
    else:
        # Deterministic fallback: pick station with minimum estimated journey time
        chosen_id = min(
            actions,
            key=lambda s_id: fallback_times_map[s_id]
        )
        decision_mode = "deterministic_fallback"
        fallback_status = True
        predicted_q = agent.get_q_value(contexts[chosen_id], chosen_id)

    chosen_station = station_map[chosen_id]
    times = calculated_times[chosen_id]

    return {
        "status": "success",
        "station": chosen_station,
        "station_id": chosen_id,
        "station_name": chosen_station.get("name", f"Station {chosen_id}"),
        "context": contexts[chosen_id],
        "all_station_contexts": contexts,
        "estimated_travel_time": f"{times['travel_time']} min",
        "estimated_travel_time_minutes": times['travel_time'],
        "estimated_waiting_time": f"{times['waiting_time']} min",
        "estimated_waiting_time_minutes": times['waiting_time'],
        "estimated_total_journey_time": f"{times['total_journey_time']} min",
        "estimated_total_journey_time_minutes": times['total_journey_time'],
        "predicted_q_value": predicted_q,
        "decision_mode": decision_mode,
        "fallback_status": fallback_status,
        "is_simulated": True,
        "disclaimer": SIMULATION_DISCLAIMER
    }


