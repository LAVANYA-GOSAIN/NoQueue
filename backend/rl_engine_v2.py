class CNGEnvironment:
    """
    Simulated environment providing station-specific contexts and journey rewards.
    """

    def __init__(self, stations: List[Dict[str, Any]]):
        self.stations = stations
        self.station_map = {
            station["id"]: station for station in stations
        }
        self.queues: Dict[int, QueueSimulator] = {}
        self.scenario_data: Dict[int, Dict[str, Any]] = {}

        self.reset()

    def load_scenarios(self) -> List[Dict[str, Any]]:
        """Read generated scenarios from the synthetic CSV."""
        if not os.path.exists(DATASET_PATH):
            raise FileNotFoundError(
                f"Synthetic dataset not found: {DATASET_PATH}"
            )

        with open(DATASET_PATH, "r", newline="") as file:
            return list(csv.DictReader(file))

    def reset(self) -> Dict[int, str]:
        """
        Start a new recommendation scenario by sampling conditions
        independently for each station.
        """
        scenarios = self.load_scenarios()

        for station in self.stations:
            station_id = station["id"]
            matching = [
                row for row in scenarios
                if int(row["station_id"]) == station_id
            ]

            if not matching:
                raise ValueError(
                    f"No scenarios found for station {station_id}"
                )

            selected = random.choice(matching)
            self.scenario_data[station_id] = selected

            self.queues[station_id] = QueueSimulator(
                initial_queue=int(selected["vehicles_in_queue"]),
                arrival_rate=float(selected["arrival_rate_per_minute"]),
                service_rate=float(selected["service_rate_per_minute"])
            )

        return self.get_all_contexts()

    def get_station_context(self, station_id: int) -> str:
        """
        Constructs the station-specific context string:
        S{station_id}_{traffic_level}_{queue_level}
        """
        queue_size = self.queues[station_id].queue
        if queue_size <= 5:
            queue_level = "LOW"
        elif queue_size <= 12:
            queue_level = "MODERATE"
        else:
            queue_level = "HIGH"

        traffic_level = self.scenario_data[station_id]["traffic_level"].upper()
        return f"S{station_id}_{traffic_level}_{queue_level}"

    def get_all_contexts(self) -> Dict[int, str]:
        """Returns station_id -> station_context mapping for all stations."""
        return {
            station_id: self.get_station_context(station_id)
            for station_id in sorted(self.queues)
        }

    def get_state(self) -> str:
        """Legacy helper returning joined contexts for inspection."""
        contexts = self.get_all_contexts()
        return "|".join(contexts[s_id] for s_id in sorted(contexts))

    def get_available_actions(self) -> List[int]:
        return list(self.station_map.keys())

    def get_deterministic_journey_times(self) -> Dict[int, float]:
        """
        Calculates deterministic journey time for each station under current conditions.
        Used as consistent baseline and fallback.
        """
        times = {}
        for station_id, station in self.station_map.items():
            traffic = self.scenario_data[station_id]["traffic_level"].upper()
            traffic_mult = {
                "LOW": 0.8,
                "MODERATE": 1.0,
                "HEAVY": 1.5
            }.get(traffic, 1.0)

            travel_time = round(station["base_travel_time"] * traffic_mult, 2)
            waiting_time = self.queues[station_id].estimate_waiting_time()
            times[station_id] = round(travel_time + waiting_time, 2)
        return times

    def step(
        self,
        action_station_id: int
    ) -> Tuple[Dict[int, str], float, Dict[str, Any]]:
        """
        Execute selecting a station. Calculates travel time, waiting time,
        and returns reward = -total_journey_time.
        """
        if action_station_id not in self.station_map:
            raise ValueError("Invalid station selected.")

        station = self.station_map[action_station_id]
        simulator = self.queues[action_station_id]
        traffic = self.scenario_data[action_station_id]["traffic_level"].upper()

        traffic_multiplier = {
            "LOW": 0.8,
            "MODERATE": 1.0,
            "HEAVY": 1.5
        }.get(traffic, 1.0)

        travel_time = round(
            station["base_travel_time"] * traffic_multiplier,
            2
        )
        waiting_time = simulator.estimate_waiting_time()
        total_journey_time = round(travel_time + waiting_time, 2)
        reward = -total_journey_time

        # Advance queues by one simulated minute
        queue_updates = {}
        for station_id, queue_sim in self.queues.items():
            queue_updates[station_id] = queue_sim.step()

        next_contexts = self.get_all_contexts()

        details = {
            "station_id": action_station_id,
            "station_name": station["name"],
            "travel_time": travel_time,
            "waiting_time": waiting_time,
            "total_journey_time": total_journey_time,
            "reward": reward,
            "queue_updates": queue_updates,
            "data_source": "synthetic",
            "is_simulated": True
        }

        return next_contexts, reward, details


