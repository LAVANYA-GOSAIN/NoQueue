def refresh_location() -> Dict[str, Any]:
    """
    Advances simulation by one step for the active discovered location's verified stations
    and updates queue telemetry and the recommendation without re-fetching OSM.
    """
    global active_location_snapshot
    if not active_location_snapshot:
        return {
            "status": "no_active_location",
            "message": "No active location discovery to refresh.",
            "recommendation": None,
            "verified_cng_stations": [],
        }

    active_scenario = active_location_snapshot.get("synthetic_scenario", DEFAULT_DISCOVERED_SCENARIO)
    attach_telemetry_and_recommend(
        active_location_snapshot,
        advance_simulation=True,
        scenario=active_scenario
    )
    active_location_snapshot["last_updated"] = datetime.datetime.now().isoformat()
    return active_location_snapshot


