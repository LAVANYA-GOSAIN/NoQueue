@app.get("/api/location/discover")
def discover_location(
    query: Optional[str] = Query(None, description="Location, locality, city, or pincode to search"),
    lat: Optional[float] = Query(None, ge=-90.0, le=90.0, description="Latitude for direct coordinate discovery"),
    lon: Optional[float] = Query(None, ge=-180.0, le=180.0, description="Longitude for direct coordinate discovery"),
    radius: int = Query(5000, ge=500, le=25000, description="Search radius in meters (default: 5000)"),
    scenario: Optional[str] = Query(None, description="Explicit synthetic scenario: LOW, MODERATE, or HEAVY (default: MODERATE)"),
) -> Dict[str, Any]:
    """
    Discovers nearby fuel stations using OpenStreetMap, distinguishing verified CNG stations
    (explicitly tagged fuel:cng=yes) from unverified fuel stations.

    Supports:
    1. Direct coordinate discovery from selected Photon autocomplete suggestions or browser GPS.
    2. Reliable text-based geocoding using OpenStreetMap Nominatim with retry and country scoping.
    3. Explicit synthetic queue scenario selection (LOW, MODERATE, or HEAVY), defaulting to MODERATE.
    """
    radius_val = 5000
    if isinstance(radius, (int, float)):
        radius_val = int(radius)

    # 1. Coordinate-based discovery (from Photon autocomplete or browser Geolocation)
    if isinstance(lat, (int, float)) and isinstance(lon, (int, float)):
        if not (-90.0 <= lat <= 90.0 and -180.0 <= lon <= 180.0):
            raise HTTPException(
                status_code=400,
                detail="Invalid coordinates: latitude must be between -90 and 90, longitude between -180 and 180.",
            )

        location_label = query.strip() if (isinstance(query, str) and query.strip()) else None
        reverse_info = reverse_geocode(lat, lon)
        display_name = location_label or reverse_info.get("display_name", f"Location ({round(lat, 4)}° N, {round(lon, 4)}° E)")

        discovery_result = discover_nearby_stations(
            lat=lat,
            lon=lon,
            radius_meters=radius_val,
        )

        resp = {
            "status": "success",
            "query": location_label or display_name,
            "resolved_location": {
                "display_name": display_name,
                "latitude": lat,
                "longitude": lon,
                "address": reverse_info.get("address", {}),
                "osm_type": reverse_info.get("osm_type"),
                "osm_id": reverse_info.get("osm_id"),
            },
            "search_radius_km": radius_val / 1000.0,
            "data_source": "openstreetmap",
            "discovery_engine": discovery_result.get("discovery_engine", "openstreetmap"),
            "total_stations_found": discovery_result["total_stations_found"],
            "verified_cng_count": discovery_result["verified_cng_count"],
            "other_fuel_count": discovery_result["other_fuel_count"],
            "message": discovery_result["message"],
            "verified_cng_stations": discovery_result["verified_cng_stations"],
            "other_fuel_stations": discovery_result["other_fuel_stations"],
        }
        attach_telemetry_and_recommend(resp, advance_simulation=False, scenario=scenario)
        global active_location_snapshot
        active_location_snapshot = resp
        return resp

    # 2. Text-based query discovery (manual search / enter key / chip)
    clean_query = query.strip() if isinstance(query, str) else ""
    if len(clean_query) < 2:
        raise HTTPException(
            status_code=400,
            detail="Please provide a location query with at least 2 characters or valid coordinates (lat, lon).",
        )

    try:
        resolved = geocode_location(clean_query)
    except GeocodingServiceError as gse:
        raise HTTPException(
            status_code=gse.status_code,
            detail=str(gse),
        )
    except Exception as exc:
        raise HTTPException(
            status_code=503,
            detail=f"Geocoding service encountered an unexpected error: {exc}",
        )

    if not resolved:
        raise HTTPException(
            status_code=404,
            detail=f"Could not find coordinates for location '{clean_query}'. Please verify the locality, city, or pincode.",
        )

    discovery_result = discover_nearby_stations(
        lat=resolved["lat"],
        lon=resolved["lon"],
        radius_meters=radius_val,
    )

    resp = {
        "status": "success",
        "query": clean_query,
        "resolved_location": {
            "display_name": resolved["display_name"],
            "latitude": resolved["lat"],
            "longitude": resolved["lon"],
            "address": resolved.get("address", {}),
            "osm_type": resolved.get("osm_type"),
            "osm_id": resolved.get("osm_id"),
        },
        "search_radius_km": radius_val / 1000.0,
        "data_source": "openstreetmap",
        "discovery_engine": discovery_result.get("discovery_engine", "openstreetmap"),
        "total_stations_found": discovery_result["total_stations_found"],
        "verified_cng_count": discovery_result["verified_cng_count"],
        "other_fuel_count": discovery_result["other_fuel_count"],
        "message": discovery_result["message"],
        "verified_cng_stations": discovery_result["verified_cng_stations"],
        "other_fuel_stations": discovery_result["other_fuel_stations"],
    }
    attach_telemetry_and_recommend(resp, advance_simulation=False, scenario=scenario)
    active_location_snapshot = resp
    return resp


