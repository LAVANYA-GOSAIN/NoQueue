class DiscoveredSimulatorsMap(dict):
    """
    Transparent container supporting both (osm_id, scenario) tuple keys
    and legacy integer osm_id keys for full backward compatibility.
    """
    def __contains__(self, key):
        if super().__contains__(key):
            return True
        if isinstance(key, int):
            return any(k[0] == key for k in self.keys() if isinstance(k, tuple))
        return False

    def __getitem__(self, key):
        if super().__contains__(key):
            return super().__getitem__(key)
        if isinstance(key, int):
            for k in reversed(list(self.keys())):
                if isinstance(k, tuple) and k[0] == key:
                    return super().__getitem__(k)
        raise KeyError(key)

    def get(self, key, default=None):
        try:
            return self[key]
        except KeyError:
            return default


